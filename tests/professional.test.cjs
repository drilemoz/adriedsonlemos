const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(dir,'index.html'),'utf8');
const css = fs.readFileSync(path.join(dir,'styles.css'),'utf8');
const readme = fs.readFileSync(path.join(dir,'README.md'),'utf8');
const pdf = fs.readFileSync(path.join(dir,'assets/docs/curriculo-adriedson-lemos.pdf'));
assert.ok(pdf.slice(0,8).toString().startsWith('%PDF-'));
assert.ok(pdf.byteLength>15000,'PDF real e incorporado');
for (const id of ['experiencia','habilidades','projetos','contato']) assert.ok(html.includes('id="'+id+'"'),id);
for (const employer of ['Atacadão','MEDGRUPO','Prefeitura de Iguatama']) assert.ok(html.includes(employer), employer);
assert.ok(html.includes('graduação trancada'));
assert.ok(html.includes('Baixar currículo'));
assert.ok(html.includes('curriculo-adriedson-lemos.pdf'));
assert.match(css,/\.career-grid/);
assert.match(css,/\.skills-grid/);
assert.doesNotMatch(html,/CID\s*H54|visão monocular|solteiro|sem filhos|href="tel:/i);
assert.match(readme,/1\.5\.0/);
console.log('Experiência, competências, currículo e privacidade pública validados.');
