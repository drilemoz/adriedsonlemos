const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname,'..');
const html = fs.readFileSync(path.join(dir,'index.html'),'utf8');
const css = fs.readFileSync(path.join(dir,'styles.css'),'utf8');
const version = fs.readFileSync(path.join(dir,'VERSION'),'utf8').trim();
const code = Number(fs.readFileSync(path.join(dir,'VERSION_CODE'),'utf8').trim());
const meta = JSON.parse(fs.readFileSync(path.join(dir,'github-manager.json'),'utf8'));
assert.match(version,/^\d+\.\d+\.\d+$/);
assert.equal(version,'1.2.0');
assert.equal(meta.version,version);
assert.equal(meta.versionName,version);
assert.equal(meta.build,code);
assert.equal(meta.versionCode,code);
assert.equal(meta.repository,'drilemoz/adriedsonlemos');
assert.match(meta.projectType,/website/);
assert.match(html,new RegExp('Versão do portal\\s*<strong>v'+version.replaceAll('.','\\.')+'</strong>'));
assert.match(html,/href="mailto:drilemoz@gmail\.com"/);
assert.match(html,/href="tel:\+5537998747642"/);
assert.match(html,/\+55 \(37\) 99874-7642/);
assert.match(html,/https:\/\/github\.com\/drilemoz\/adriedsonlemos\/blob\/main\/CHANGELOG\.md/);
assert.match(css,/\.contact-methods/);
assert.match(css,/\.footer-version/);
assert.match(css,/#08090c/);
console.log('Identidade, contatos públicos, versão e estilos validados.');
